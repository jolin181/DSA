import java.util.*;
public class perfectroot {
    public static void main(String[] args){
        Scanner sc=new Scanner(System.in);
        int times=sc.nextInt();
        while(times-->0){
            int n= sc.nextInt();
            for(int i=1;i<=n;i++){
                System.out.print(i+" ");
            }
            System.out.println();
        }

    }
}
